export function joinNames(names: string[], locale: Locale): string {
  if (names.length <= 1) return names[0] ?? ''
  const lead = names.slice(0, -1).join(', ')
  return locale === 'nb' ? `${lead} og ${names.at(-1)}` : `${lead} and ${names.at(-1)}`
}

export function foodName(id: string, english: string, locale: Locale): string {
  if (locale === 'en') return english
  return NB_FOODS[id] ?? english
}

export function categoryName(category: string, locale: Locale): string {
  if (locale === 'en') return category
  return NB_CATEGORIES[category] ?? category
}
