import type { Locale } from './i18n'

const w = (file: string) =>
  `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}?width=500`

const m = (name: string) =>
  `https://www.themealdb.com/images/ingredients/${encodeURIComponent(name)}.png`

const pixar = (name: string) =>
  `https://api.iconify.design/fluent-emoji-3d:${name}.png?height=256`

export type FoodImage = {
  src: string
  fit: 'contain'
}

type Entry = {
  icon: string
  both?: FoodImage[]
  nb?: FoodImage[]
  en?: FoodImage[]
}

const wiki = (file: string): FoodImage => ({ src: w(file), fit: 'contain' })
const meal = (name: string): FoodImage => ({ src: m(name), fit: 'contain' })
const icon = (name: string): FoodImage => ({ src: pixar(name), fit: 'contain' })

export function imagesFor(id: string, locale: Locale): FoodImage[] {
  const entry = FOOD_IMAGES[id]
  if (!entry) return [icon('cooked-food')]
  const local = locale === 'nb' ? entry.nb : entry.en
  return [...(local ?? []), ...(entry.both ?? []), icon(entry.icon)]
}

